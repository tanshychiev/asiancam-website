function toggleMenu() {
const menu =
document.getElementById("mainMenu") ||
document.querySelector(".menu");

if (!menu) {
return;
}

menu.classList.toggle("active");
menu.classList.toggle("open");
menu.classList.toggle("show");
}

function normalizeLang(lang) {
return ["en", "kh", "cn"].includes(lang) ? lang : "en";
}

function setLang(lang) {
const selectedLang = normalizeLang(lang);

localStorage.setItem("asiancam_lang", selectedLang);
applyLang(selectedLang);
}

function applyLang(lang) {
const selectedLang = normalizeLang(lang);
const dict = translations[selectedLang] || translations.en;
const html = document.documentElement;

html.lang =
selectedLang === "kh"
? "km"
: selectedLang === "cn"
? "zh"
: "en";

html.setAttribute("data-lang", selectedLang);

if (document.body) {
document.body.classList.remove(
"khmer",
"chinese",
"lang-en",
"lang-kh",
"lang-cn"
);

document.body.classList.add("lang-" + selectedLang);

if (selectedLang === "kh") {
  document.body.classList.add("khmer");
}

if (selectedLang === "cn") {
  document.body.classList.add("chinese");
}

}

document.querySelectorAll("[data-i18n]").forEach(function (element) {
const key = element.getAttribute("data-i18n");

if (Object.prototype.hasOwnProperty.call(dict, key)) {
  element.textContent = dict[key];
}

});

document
.querySelectorAll("[data-i18n-placeholder]")
.forEach(function (element) {
const key = element.getAttribute("data-i18n-placeholder");

  if (Object.prototype.hasOwnProperty.call(dict, key)) {
    element.placeholder = dict[key];
  }
});

document
.querySelectorAll("[data-i18n-title]")
.forEach(function (element) {
const key = element.getAttribute("data-i18n-title");

  if (Object.prototype.hasOwnProperty.call(dict, key)) {
    element.title = dict[key];
  }
});

document
.querySelectorAll("[data-i18n-alt]")
.forEach(function (element) {
const key = element.getAttribute("data-i18n-alt");

  if (Object.prototype.hasOwnProperty.call(dict, key)) {
    element.alt = dict[key];
  }
});

document
.querySelectorAll(".langs button, .lang-btn")
.forEach(function (button) {
const isActive = button.dataset.lang === selectedLang;

  button.classList.toggle("active", isActive);
  button.setAttribute("aria-pressed", isActive ? "true" : "false");
});

localStorage.setItem("asiancam_lang", selectedLang);
}

window.toggleMenu = toggleMenu;
window.setLang = setLang;
window.applyLang = applyLang;

document.addEventListener("DOMContentLoaded", function () {
const savedLang =
localStorage.getItem("asiancam_lang") ||
localStorage.getItem("siteLang") ||
localStorage.getItem("lang") ||
"en";

applyLang(savedLang);
});
